#ifndef INCLUDE_TYPES_H
#define INCLUDE_TYPES_H

/* shortened names for fixed-sized numbers */
typedef unsigned int   u32int;   
/* 32bit unsigned int */
typedef int            s32int;   
/* 32bit signed int */
typedef unsigned short u16int;   
/* 16bit unsigned int */
typedef short          s16int;   
/* 16bit signed int */
typedef unsigned char  u8int;    
/* 8bit (1byte) unsigned int */
typedef char           s8int;    
/* 8bit signed int */

/* framebuffer colours*/
#define BLACK      0
#define BLUE       1
#define LIGHT_GREY 7

#endif